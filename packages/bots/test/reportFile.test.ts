import { describe, expect, it } from 'vitest'
import { asSection, mergeReportFile, NOTES_HEADING } from '../src/reportFile'

const report = (n: number) =>
  [
    '# Balancing report',
    '',
    `Generated by \`pnpm bots --runs ${n} --seed-prefix test\`, engine x.`,
    '',
    '## Targets (plan section 7)',
    '',
    '| # | Target |',
    '',
  ].join('\n')

const order = [
  { id: 'kantino', name: 'Kantino' },
  { id: 'zollstock', name: 'Zollstock' },
]

describe('the report file', () => {
  it('turns a report into a scenario section with the scenario in its command', () => {
    const section = asSection(report(10), order[0]!)
    expect(section.split('\n')[0]).toBe('# Kantino')
    expect(section).toContain('`pnpm bots --runs 10 --seed-prefix test --scenario kantino`')
    expect(section).toContain('## Targets (plan section 7)\n\n| # | Target |\n')
  })

  it('replaces the sections run, keeps the others and the notes, in scenario order', () => {
    const notes = `${NOTES_HEADING}\n\nHand written.\n\n## Kantino\n\n### Round 1\n`
    const first = mergeReportFile(
      `${notes}`,
      order,
      new Map([
        ['zollstock', asSection(report(1), order[1]!)],
        ['kantino', asSection(report(2), order[0]!)],
      ]),
    )
    expect(first.indexOf('# Kantino')).toBeLessThan(first.indexOf('# Zollstock'))
    expect(first.trimEnd().endsWith('### Round 1')).toBe(true)
    const second = mergeReportFile(
      first,
      order,
      new Map([['kantino', asSection(report(3), order[0]!)]]),
    )
    expect(second).toContain('--runs 3 --seed-prefix test --scenario kantino')
    expect(second).not.toContain('--runs 2 ')
    expect(second).toContain('--runs 1 --seed-prefix test --scenario zollstock')
    expect(second).toContain('Hand written.')
    expect(second.match(/^# /gm)).toHaveLength(4)
  })
})
