/**
 * docs/balancing.md holds one section per scenario, then the hand written tuning notes. A run of
 * some scenarios replaces their sections and keeps everything else.
 */

/** Heading of the hand written part, kept when the report is rebuilt. */
export const NOTES_HEADING = '# Tuning notes'

const PREAMBLE = [
  '# Balancing report',
  '',
  'One section per scenario and mode, each with its own targets (plan section 7 and `docs/phase9-proposal.md`). `pnpm bots --runs 1000 --seed-prefix test --events` runs every scenario in the 60 week game; `--scenario <id>` runs one, `--mode long` or `--mode all` the long mode, and every other section is kept. The hand written tuning notes are at the end.',
  '',
].join('\n')

/**
 * One section of the file: a scenario in one mode. `id` keys the section, `name` is its title and
 * `flags` what its command line adds (`--scenario kantino --mode long`).
 */
export type ScenarioSection = { id: string; name: string; flags: string }

/**
 * Turns a scenario's report (as `buildReport` writes it) into its section of the file: the
 * scenario's name as the title and its id in the command line.
 */
export function asSection(report: string, scenario: ScenarioSection): string {
  const [first, ...rest] = report.split('\n')
  if (first !== '# Balancing report') throw new Error('Unexpected report title')
  const body = rest.join('\n').replace(/(Generated by `pnpm bots [^`]*)`/, `$1 ${scenario.flags}\``)
  return `# ${scenario.name}\n${body.trimEnd()}\n`
}

/** Splits a file into its top level (`# `) blocks, keyed by their title line. */
function blocks(text: string): Map<string, string> {
  const out = new Map<string, string>()
  const lines = text.split('\n')
  let title: string | null = null
  let start = 0
  const close = (end: number) => {
    if (title !== null) out.set(title, `${lines.slice(start, end).join('\n').trimEnd()}\n`)
  }
  lines.forEach((line, i) => {
    if (!line.startsWith('# ')) return
    close(i)
    title = line
    start = i
  })
  close(lines.length)
  return out
}

/**
 * The new file: the preamble, every scenario in `order` (its new section if given, else the old
 * one if the file had it), then the old tuning notes.
 */
export function mergeReportFile(
  old: string | null,
  order: readonly ScenarioSection[],
  sections: ReadonlyMap<string, string>,
): string {
  const previous = blocks(old ?? '')
  const parts = [PREAMBLE]
  for (const s of order) {
    const section = sections.get(s.id) ?? previous.get(`# ${s.name}`)
    if (section) parts.push(section)
  }
  parts.push(previous.get(NOTES_HEADING) ?? `${NOTES_HEADING}\n`)
  return parts.join('\n')
}
