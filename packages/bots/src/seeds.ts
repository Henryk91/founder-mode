// Writes docs/seeds.md: two or three seeds per scenario and ending, with the bot that gets there.
// Run with `pnpm seeds`. test/seeds.test.ts replays every row of the file.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { loadScenario, SCENARIO_IDS } from '@founder-mode/content'
import { ENGINE_VERSION } from '@founder-mode/engine'
import { findEndingSeeds, seedsTable } from './endingSeeds'

const OUT = fileURLToPath(new URL('../../../docs/seeds.md', import.meta.url))

const rows = SCENARIO_IDS.flatMap((id) => findEndingSeeds(loadScenario(id), 3))

const doc = `# Seeds per ending

Known seeds that reach each ending, with the bot strategy that plays them there. Use them to look at an ending's screens, its post-mortem, or a bug report about one.

Generated by \`pnpm seeds\` (engine ${ENGINE_VERSION}). Do not edit the table by hand.

## How to use a seed

- On the Start screen, pick the scenario, type the seed into "Seed (optional)" and press New run. This works in every build. The seed fixes the market and the luck; the ending also depends on how the run is played.
- To get the ending in the table, play the run as its strategy does. Each strategy is described at the top of its file in \`packages/bots/src/strategies/\`, and \`playSeed(scenario, strategy, seed)\` in \`packages/bots/src/endingSeeds.ts\` replays it.
- \`shut_down@10\` means the careful bot (\`validate_then_build\`) plays to week 10 and then shuts the company down. No bot quits on its own; only the player can.

## When the list goes stale

Any change to the engine, to scenario values or texts, or to a bot strategy can change where a seed ends up. \`packages/bots/test/seeds.test.ts\` replays every row and fails when one no longer reaches its ending or week. Then run \`pnpm seeds\` to find new seeds and rewrite this file, and commit it with the change.

## Seeds

${seedsTable(rows)}
`

writeFileSync(OUT, doc)
console.log(`Wrote ${rows.length} seeds to docs/seeds.md`)
